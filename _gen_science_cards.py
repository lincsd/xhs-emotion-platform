def generate_all():
    """生成所有缺失的知识卡 JSON 文件"""
    count = 0
    for (stage, subject, grade_short, grade_full, semester), units in COURSE_DATA.items():
        for kc_dir in ['knowledge_cards', os.path.join('public', 'knowledge_cards')]:
            dir_path = os.path.join(BASE_DIR, kc_dir, stage)
            os.makedirs(dir_path, exist_ok=True)
            
            filepath = os.path.join(dir_path, f'{subject}_{grade_short}_总结.json')
            
            if os.path.exists(filepath):
                print(f'  ⏭️  已存在: {os.path.relpath(filepath, BASE_DIR)}')
                continue
            
            # 构造 JSON
            total_cards = sum(len(u['cards']) for u in units)
            
            # 添加 full_id 到每张卡片
            for unit in units:
                for card in unit['cards']:
                    if 'full_id' not in card:
                        card['full_id'] = f"{subject}-{grade_short}-{card['card_id']}"
            
            data = {
                "subject": subject,
                "grade": f"{grade_full}年级" if '年级' not in grade_full else grade_full,
                "semester": semester,
                "textbook": "人教版",
                "grade_short": grade_short,
                "card_pack": "知识总结",
                "description": f"{stage}{grade_full}{semester}{subject}中考/高考考点笔记总结",
                "units": units,
            }
            
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
            
            rel = os.path.relpath(filepath, BASE_DIR)
            print(f'  ✅ 创建: {rel} ({total_cards} cards)')
            count += 1
    
    print(f'\n总计创建 {count} 个文件')


if __name__ == '__main__':
    generate_all()
